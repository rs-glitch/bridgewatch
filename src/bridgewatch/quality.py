"""Data-quality report over the bridge-year panel. Writes reports/data_quality.md and reports/data_quality.json.

Every number in the report is computed here from data/panel; nothing is typed by hand.
"""

import json

from .db import connect
from .paths import KEYED, PANEL, REPORTS

POSTING = {"A": "open", "B": "open, work pending", "D": "open, temp shoring", "E": "open, temp structure", "G": "new, not open",
           "K": "closed", "P": "posted for load", "R": "posted, other restriction"}


def _q(con, sql):
    return con.execute(sql).fetchall()


def build_report() -> dict:
    con = connect()
    con.execute(f"CREATE VIEW p AS SELECT * FROM read_parquet('{KEYED}/nbi_*.parquet')")
    log = {r["year"]: r for r in json.loads((PANEL / "build_log.json").read_text())}

    per_year = _q(con, """
        SELECT year, count(*) n,
               avg((lat IS NOT NULL)::INT) located,
               avg((lowest_rating IS NOT NULL)::INT) rated,
               avg((condition='Good')::INT) good, avg((condition='Fair')::INT) fair, avg((condition='Poor')::INT) poor,
               avg((posting_status IN ('P','R','K'))::INT) posted_or_closed,
               avg((inspection_interval_mo BETWEEN 1 AND 96)::INT) interval_valid,
               avg((adt IS NOT NULL AND adt > 0)::INT) adt_positive
        FROM p GROUP BY year ORDER BY year""")

    churn = _q(con, """
        WITH ids AS (SELECT DISTINCT year, bridge_id FROM p)
        SELECT a.year, count(*) FILTER (WHERE b.bridge_id IS NULL) AS gone_next_year,
               count(*) AS n
        FROM ids a LEFT JOIN ids b ON a.bridge_id = b.bridge_id AND b.year = a.year + 1
        WHERE a.year < (SELECT max(year) FROM ids) GROUP BY a.year ORDER BY a.year""")

    span = _q(con, """
        SELECT count(*) bridges, avg(n) mean_years, median(n) median_years,
               avg((n = (SELECT count(DISTINCT year) FROM p))::INT) in_every_year
        FROM (SELECT bridge_id, count(*) n FROM p GROUP BY bridge_id)""")[0]

    rating_jumps = _q(con, """
        WITH s AS (SELECT bridge_id, year, deck, superstructure, substructure,
                          lag(deck) OVER w d0, lag(superstructure) OVER w s0, lag(substructure) OVER w b0, lag(year) OVER w y0
                   FROM p WINDOW w AS (PARTITION BY bridge_id ORDER BY year))
        SELECT avg((deck - d0 >= 2)::INT), avg((superstructure - s0 >= 2)::INT), avg((substructure - b0 >= 2)::INT),
               avg((d0 - deck >= 3)::INT), avg((s0 - superstructure >= 3)::INT), avg((b0 - substructure >= 3)::INT)
        FROM s WHERE y0 = year - 1 AND d0 IS NOT NULL AND deck IS NOT NULL""")[0]

    posting_mix = _q(con, "SELECT posting_status, count(*) FROM p WHERE year = (SELECT max(year) FROM p) GROUP BY 1 ORDER BY 2 DESC")
    interval_mix = _q(con, """SELECT inspection_interval_mo, count(*) FROM p WHERE year = (SELECT max(year) FROM p)
                              GROUP BY 1 ORDER BY 2 DESC LIMIT 8""")
    out = {
        "per_year": [dict(zip(["year", "bridges", "located", "rated", "good", "fair", "poor", "posted_or_closed", "interval_valid",
                               "adt_positive"], r, strict=True)) for r in per_year],
        "malformed_rows_dropped": {y: log[y].get("malformed_rows_dropped") for y in sorted(log)},
        "gone_next_year": [{"year": y, "share": g / n} for y, g, n in churn],
        "history": dict(zip(["bridges_ever", "mean_years", "median_years", "share_in_every_year"], span, strict=True)),
        "one_year_jumps": dict(zip(["deck_up_2plus", "super_up_2plus", "sub_up_2plus", "deck_down_3plus", "super_down_3plus",
                                    "sub_down_3plus"], rating_jumps, strict=True)),
        "latest_posting_mix": posting_mix,
        "latest_interval_mix": interval_mix,
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "data_quality.json").write_text(json.dumps(out, indent=1, default=float))
    (REPORTS / "data_quality.md").write_text(_markdown(out))
    return out


def _pct(x):
    return f"{100 * x:.1f}%"


def _markdown(o) -> str:
    h = o["history"]
    lines = ["# NBI panel: data-quality report", "",
             "Generated by `bridgewatch quality` from `data/panel_keyed` (IDs linked across renumberings).",
             "Record type 1 rows only (the route carried on the structure).", "",
             "## Coverage by year", "",
             "| Year | Bridges | Located | Rated | Good | Fair | Poor | Posted/closed | Valid interval | ADT > 0 | Malformed rows |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in o["per_year"]:
        lines.append(f"| {r['year']} | {r['bridges']:,} | {_pct(r['located'])} | {_pct(r['rated'])} | {_pct(r['good'])} | "
                     f"{_pct(r['fair'])} | {_pct(r['poor'])} | {_pct(r['posted_or_closed'])} | {_pct(r['interval_valid'])} | "
                     f"{_pct(r['adt_positive'])} | {o['malformed_rows_dropped'].get(r['year'], 0)} |")
    lines += ["", "Condition follows FHWA: the lowest of deck, superstructure, substructure and culvert ratings;",
              "≤ 4 Poor, 5-6 Fair, ≥ 7 Good.",
              "", "## Bridge histories", "",
              f"- Distinct bridge IDs ever seen: **{h['bridges_ever']:,}**",
              f"- Years per bridge: mean {h['mean_years']:.1f}, median {h['median_years']:.0f}; "
              f"present in every year: {_pct(h['share_in_every_year'])}",
              "- Share of IDs missing the following year (replaced, renumbered or removed):", ""]
    lines += ["| Year | Gone next year |", "|---|---|"] + [f"| {g['year']} | {_pct(g['share'])} |" for g in o["gone_next_year"]]
    j = o["one_year_jumps"]
    lines += ["", "## Suspicious one-year rating changes (consecutive years only)", "",
              "| Component | Up ≥ 2 in one year (repair or re-rating) | Down ≥ 3 in one year (damage or re-rating) |", "|---|---|---|",
              f"| Deck | {_pct(j['deck_up_2plus'])} | {_pct(j['deck_down_3plus'])} |",
              f"| Superstructure | {_pct(j['super_up_2plus'])} | {_pct(j['super_down_3plus'])} |",
              f"| Substructure | {_pct(j['sub_up_2plus'])} | {_pct(j['sub_down_3plus'])} |",
              "", "## Latest year: posting status (item 41)", "", "| Code | Meaning | Bridges |", "|---|---|---|"]
    lines += [f"| {c or '(blank)'} | {POSTING.get(c, '?')} | {n:,} |" for c, n in o["latest_posting_mix"]]
    lines += ["", "## Latest year: inspection interval (item 91, months)", "", "| Months | Bridges |", "|---|---|"]
    lines += [f"| {m} | {n:,} |" for m, n in o["latest_interval_mix"]]
    return "\n".join(lines) + "\n"
