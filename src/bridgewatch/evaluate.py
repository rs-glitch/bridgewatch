"""Run the backtest folds for every method and write reports/backtest.json and reports/backtest.md."""

import json
import time

import numpy as np
import polars as pl

from . import backtest
from .baselines import Climatology, Markov, RatingLookup, TimeInCondition
from .model import GBM
from .paths import REPORTS

# (target, horizon, test year): outcomes must be observed by 2025, the last NBI year in the old format
FOLDS = [("poor", 2, 2019), ("poor", 2, 2023), ("poor", 4, 2017), ("poor", 4, 2021), ("poor", 8, 2013), ("poor", 8, 2017),
         ("restricted", 2, 2019), ("restricted", 2, 2023), ("restricted", 4, 2017), ("restricted", 4, 2021)]
# Never used for training by any method; scored separately to test transfer to an agency the model has not seen.
HOLDOUT_STATES = ("19", "48", "42", "06", "13")  # Iowa, Texas, Pennsylvania, California, Georgia


def methods(target, h, train_years, extra=()):
    m = [Climatology(), RatingLookup(), TimeInCondition()]
    if target == "poor":
        m.append(Markov(train_years, h, exclude_states=HOLDOUT_STATES))
    return m + list(extra)


def with_model(target, h):
    return [GBM()]


def run(folds=FOLDS, extra_methods=with_model, out_name="backtest"):
    results = []
    for target, h, year in folds:
        t0 = time.time()
        train, test = backtest.fold(h, year, target, HOLDOUT_STATES)
        train_years = range(year - h - backtest.TRAIN_YEARS + 1, year - h + 1)
        is_hold = test["state_code"].is_in(list(HOLDOUT_STATES)).to_numpy()
        y = test["y"].cast(pl.Float64).to_numpy()
        base = float(train["y"].mean())
        for m in methods(target, h, train_years, extra_methods(target, h) if extra_methods else ()):
            m.fit(train)
            p = np.asarray(m.predict(test), dtype=float)
            for split, mask in (("seen_states", ~is_hold), ("holdout_states", is_hold)):
                r = backtest.score(y[mask], p[mask], base) | {"target": target, "h": h, "test_year": year, "method": m.name,
                                                              "split": split, "train_rows": train.height}
                results.append(r)
        print(f"{target} h={h} T={year}: train {train.height:,} test {test.height:,} ({time.time() - t0:.0f}s)", flush=True)
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / f"{out_name}.json").write_text(json.dumps(results, indent=1))
    (REPORTS / f"{out_name}.md").write_text(markdown(results))
    return results


def markdown(results) -> str:
    lines = ["# Backtest results", "",
             "Generated by `bridgewatch backtest`. Time split: train on base years whose outcomes were known by the test year;",
             "test on every eligible bridge in the test year. Hold-out states (IA, TX, PA, CA, GA) are never used for training.",
             "Brier skill is relative to the training base rate (climatology). Precision@1% = share of the top-ranked 1% that had",
             "the event. `rating_lookup` is \"rating stays the same\" turned into a probability (worst-first ranking).", ""]
    key = lambda r: (r["target"], r["h"], r["test_year"], r["split"])  # noqa: E731
    groups = {}
    for r in results:
        groups.setdefault(key(r), []).append(r)
    for (target, h, year, split), rs in sorted(groups.items()):
        r0 = rs[0]
        lines += [f"## {target}, {h}-year horizon, test year {year}, {split.replace('_', ' ')}",
                  f"{r0['n']:,} bridges, {r0['events']:,} events ({100 * r0['rate']:.2f}%)", "",
                  "| Method | Brier skill | AUC | Avg precision | Precision@1% | Precision@5% |", "|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: -r["avg_precision"]):
            lines.append(f"| {r['method']} | {r['brier_skill']:+.3f} | {r['auc']:.3f} | {r['avg_precision']:.3f} | "
                         f"{100 * r['precision_top1pct']:.1f}% | {100 * r['precision_top5pct']:.1f}% |")
        lines.append("")
    return "\n".join(lines)
